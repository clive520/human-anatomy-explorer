// 呼吸系統的 getAnatomyData 查詢函式
window.getRespiratoryData = function(meshName) {
  if (!meshName) return null;
  const clean = meshName.replace(/\.\d+$/, '').toLowerCase().trim();
  for (const [key, val] of Object.entries(window.RESPIRATORY_DATA)) {
    if (key.toLowerCase() === clean) {
      return { zh: val.zh, en: val.en, system: '呼吸系統', desc: val.desc };
    }
  }
  // 後備：根據名稱關鍵字猜測
  let zh = meshName.replace(/^VH_M_/i, '').replace(/_/g, ' ');
  zh = zh.replace(/\b\w/g, c => c.toUpperCase());
  return { zh, en: zh, system: '呼吸系統', desc: `${zh} — 呼吸系統的重要構造，參與氣體交換與空氣傳導。` };
};
